#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// TradeLog — Build Script
// Generates public/js/config.js from environment variables.
// Runs automatically on Vercel before deployment.
// For local dev: copy config.example.js → config.js manually instead.
// ═══════════════════════════════════════════════════════════════════════════

const fs   = require('fs');
const path = require('path');

const SUPABASE_URL       = process.env.SUPABASE_URL;
const SUPABASE_ANON_KEY  = process.env.SUPABASE_ANON_KEY;
const COINGECKO_API_KEY  = process.env.COINGECKO_API_KEY || '';

// Validate required vars
const missing = [];
if (!SUPABASE_URL)      missing.push('SUPABASE_URL');
if (!SUPABASE_ANON_KEY) missing.push('SUPABASE_ANON_KEY');

if (missing.length > 0) {
  console.error('');
  console.error('❌ Build failed — missing required environment variables:');
  missing.forEach(v => console.error(`   - ${v}`));
  console.error('');
  console.error('Set them in: Vercel Dashboard → Project → Settings → Environment Variables');
  console.error('');
  process.exit(1);
}

// Sanitize: prevent script injection via env var values
function sanitize(str) {
  return String(str).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '');
}

const configContent = `// ═══════════════════════════════════════════════════════════════════════════
// TradeLog — Configuration (auto-generated by scripts/build.js)
// DO NOT EDIT — this file is generated at build time from environment variables.
// To update keys, change them in Vercel Dashboard → Settings → Environment Variables.
// ═══════════════════════════════════════════════════════════════════════════

const APP_CONFIG = {
  SUPABASE_URL:       '${sanitize(SUPABASE_URL)}',
  SUPABASE_ANON_KEY:  '${sanitize(SUPABASE_ANON_KEY)}',
  COINGECKO_API_KEY:  '${sanitize(COINGECKO_API_KEY)}',
};
`;

const outPath = path.join(__dirname, '..', 'public', 'js', 'config.js');
fs.writeFileSync(outPath, configContent, 'utf8');

console.log('✅ config.js generated successfully');
console.log(`   SUPABASE_URL:      ${SUPABASE_URL.substring(0, 30)}...`);
console.log(`   SUPABASE_ANON_KEY: ${SUPABASE_ANON_KEY.substring(0, 20)}...`);
console.log(`   COINGECKO_API_KEY: ${COINGECKO_API_KEY ? COINGECKO_API_KEY.substring(0, 10) + '...' : '(not set — optional)'}`);
